import fs from "node:fs";
import type { Page } from "playwright-core";

const publicRoot = new URL("../../public/", import.meta.url);
const modulesRoot = new URL("../../node_modules/", import.meta.url);
const vendors: Record<string, string> = {
  "/vendor/marked.js": "marked/lib/marked.umd.js",
  "/vendor/purify.js": "dompurify/dist/purify.min.js",
  "/vendor/highlight.js": "@highlightjs/cdn-assets/highlight.min.js",
};
// Vendor scripts served from the repo rather than node_modules.
const repoVendors: Record<string, URL> = {
  "/vendor/scribe-md.js": new URL("../../templates/scribe-md.js", import.meta.url),
};

/** External scripts in shell order; the appearance bootstrap is generated by the server. */
export function shellScriptNames(html = fs.readFileSync(new URL("index.html", publicRoot), "utf8")): string[] {
  return Array.from(html.matchAll(/<script\b[^>]*\bsrc=["']([^"']+)["'][^>]*>/gi), ([, src]) => src.split(/[?#]/)[0])
    .filter(src => src.startsWith("./") || src in vendors || src in repoVendors)
    .map(src => src.replace(/^\.\//, ""));
}

/** Fail on startup exceptions or a stuck evaluate(), and cancel pending browser work on failure. */
export async function shellStartup(page: Page, start: () => Promise<unknown>, timeout = 5000): Promise<void> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  let onError!: (error: Error) => void;
  const failure = new Promise<never>((_resolve, reject) => {
    onError = error => reject(new Error(`Shell fixture pageerror: ${error.message}`, { cause: error }));
    page.on("pageerror", onError);
    timer = setTimeout(() => reject(new Error(`Shell fixture startup timed out after ${timeout}ms`)), timeout);
  });
  page.setDefaultTimeout(timeout);
  try {
    await Promise.race([failure, Promise.resolve().then(start)]);
  } catch (error) {
    await page.close().catch(() => {});
    throw error;
  } finally {
    clearTimeout(timer);
    page.off("pageerror", onError);
  }
}

/** Omit scripts for the complete shell; supply names for isolated function tests.
 * Subsets still follow index.html order. Transform permits exposing functions instead of booting agent.js.
 */
export async function loadShellScripts(page: Page, options: {
  scripts?: readonly string[];
  transform?: (name: string, source: string) => string;
  ready?: () => Promise<unknown>;
  timeout?: number;
} = {}): Promise<void> {
  const ordered = shellScriptNames();
  for (const name of options.scripts ?? []) {
    if (!ordered.includes(name)) throw new Error(`Shell fixture script is absent from index.html: ${name}`);
  }
  await shellStartup(page, async () => {
    // tsx adds this helper to functions passed to page.evaluate().
    await page.addScriptTag({ content: "window.__name = value => value;" });
    for (const name of ordered.filter(name => !options.scripts || options.scripts.includes(name))) {
      const file = repoVendors[name] ?? (name in vendors ? new URL(vendors[name], modulesRoot) : new URL(name, publicRoot));
      const source = fs.readFileSync(file, "utf8");
      await page.addScriptTag({ content: (options.transform?.(name, source) ?? source) + `\n//# sourceURL=scribe-fixture/${name}` });
    }
    await options.ready?.();
  }, options.timeout);
}

/** Shared subset for chat function fixtures with a deliberately minimal DOM. */
export const chatScripts = ["motion.js", "popout.js", "dom-sync.js", "audio.js", "audio-composer.js", "component-host.js", "agent-render.js", "settings-ui.js"];

export async function loadChatFixture(page: Page, agentSource: string): Promise<void> {
  await loadShellScripts(page, {
    scripts: [...chatScripts, "agent.js"],
    transform: (name, source) => name === "agent.js" ? agentSource : source,
  });
}
